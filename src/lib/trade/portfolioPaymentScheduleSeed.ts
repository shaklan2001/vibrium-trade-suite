import type {
  DealPaymentSchedule,
  PaymentCheckpoint,
  ProvenanceCite,
} from "@/types/trade";

function cite(
  dealId: string,
  dealCode: string,
  sourceId: string,
  excerpt: string,
  subject?: string,
  kind: ProvenanceCite["kind"] = "payment",
): ProvenanceCite {
  return {
    dealId,
    dealCode,
    sourceId,
    excerpt,
    subject,
    from: "accounts@snspl.in",
    kind,
  };
}

function cp(
  partial: Omit<PaymentCheckpoint, "id"> & { id?: string },
  id: string,
): PaymentCheckpoint {
  return { id, ...partial };
}

